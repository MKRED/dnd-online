import { List, Stack, Text, Title } from '@mantine/core';
import type { ReactNode } from 'react';
import {
  ABILITY_CHECK_LABELS,
  GROWTH_CHARACTER_LEVELS,
  STEP_TARGET_LABELS,
} from 'shared';

// Разделы гайда в порядке формы. Названия полей и вариантов — из shared, как в форме:
// переименуют там — поменяется и здесь.

const [L5, L11, L17] = GROWTH_CHARACTER_LEVELS;
const { attack, save, none } = ABILITY_CHECK_LABELS;

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <Stack gap={6}>
      <Title order={3}>{title}</Title>
      {children}
    </Stack>
  );
}

// «Поле» — так в тексте выглядят подписи формы.
const F = ({ children }: { children: ReactNode }) => <b>{children}</b>;

export function CategorySection() {
  return (
    <Section title="Категория">
      <Text>
        <F>Базовая</F> — всё, что не заклинание: умения класса и вида, приёмы,
        действия чудовищ. <F>Заклинание</F> добавляет круг, школу, ритуал,
        компоненты и длительность.
      </Text>
      <Text>
        Выбранный круг сам отмечает в затратах ячейку этого круга. Снимите
        галочку, если заклинание творят без ячейки — например, раз за долгий
        отдых от черты.
      </Text>
    </Section>
  );
}

export function UsageSection() {
  return (
    <Section title="Активация и затраты">
      <Text>
        <F>Активация</F> — чем способность занимает ход. Подсказка под полем
        напомнит, когда что выбирать. У реакции можно записать условие: «когда
        по вам попадает видимый враг».
      </Text>
      <Text>
        <F>Затраты</F> — отметьте всё, что тратится: свои заряды, ячейку,
        движение, кость хитов. Ничего не отмечено — способность бесплатна, как
        заговор.
      </Text>
    </Section>
  );
}

export function StepsSection() {
  return (
    <Section title="Применение: шаги">
      <Text>
        Шаг — один бросок и то, что из него выходит. Почти всем способностям
        хватает одного шага. Без шагов способность тоже сохранится — тогда всё в
        описании. Шаг заполняют сверху вниз:
      </Text>
      <List type="ordered" spacing={4}>
        <List.Item>
          <F>Проверка</F>: {attack.toLowerCase()}, {save.toLowerCase()} или{' '}
          {none.toLowerCase()} — всё проходит само.
        </List.Item>
        <List.Item>
          <F>Цель</F>: на выбор только то, что подходит проверке.
        </List.Item>
        <List.Item>
          <F>Сколько раз</F>: лучи и дротики, у каждого свой бросок.
        </List.Item>
        <List.Item>
          <F>При попадании</F> или <F>При провале</F> (без проверки —{' '}
          <F>Последствия</F>): урон — кости, число и тип, две строки — если урон
          двух типов. Под уроном — эффекты.
        </List.Item>
        <List.Item>
          <F>При промахе</F> или <F>При успехе</F> — только у шага с проверкой:
          ничего или половина урона и свои эффекты.
        </List.Item>
      </List>
      <Text>
        Бонус атаки и Сл оставьте «Характеристика + бонус мастерства» — игра
        посчитает их по персонажу. «Числом» — для чудовищ и предметов.
      </Text>
    </Section>
  );
}

export function EffectsSection() {
  return (
    <Section title="Эффекты">
      <Text>
        Состояние или другое долгое действие — эффект из раздела «Эффекты».
        Сначала создайте его там: например, «Отравлен до конца следующего хода»
        с состоянием и длительностью. Потом в шаге, под уроном, найдите его в
        поле <F>+ Эффект</F>.
      </Text>
      <Text>
        Эффект ложится на тех, кого задел исход: при попадании — на цель, при
        провале — на проваливших, при промахе — на ту же цель, при успехе — на
        устоявших. Себе — шагом «На себя» без проверки, как «Ярость». Если
        эффект снимается спасброском, его Сл — Сл спасброска шага, а у шага без
        спасброска — Сл ваших заклинаний.
      </Text>
      <Text>
        Опубликовать способность можно только вместе с её эффектами — форма
        предложит опубликовать их сама.
      </Text>
    </Section>
  );
}

export function ChainSection() {
  return (
    <Section title="Несколько шагов">
      <Text>
        Второй шаг нужен, когда после первого броска происходит что-то ещё:
        «Ледяной кинжал» попадает, а потом взрывается. У шага 2 появляется{' '}
        <F>Когда</F> — всегда, при попадании или при промахе первого — и цели «
        {STEP_TARGET_LABELS.previous}» и «{STEP_TARGET_LABELS.around}». Шагов не
        больше трёх.
      </Text>
    </Section>
  );
}

export function GrowthSection() {
  return (
    <Section title="Рост">
      <Text>
        Если урон или число повторов растут, нажмите в шаге <F>+ Рост</F>.
        Сколько прибавить, пишете вы, а когда — решает сама способность:
      </Text>
      <List spacing={4}>
        <List.Item>
          тратит ячейку — за каждый круг ячейки выше её круга;
        </List.Item>
        <List.Item>
          ячейку не тратит — на {L5}, {L11} и {L17} уровне персонажа, как
          заговоры;
        </List.Item>
        <List.Item>
          заклинание 1 круга и выше без ячейки не растёт: его творят его кругом.
        </List.Item>
      </List>
      <Text>
        Прибавку пишите за одну ступень: у «Огненного шара» 3 круга это +1d6, а
        ячейка 5 круга сама даст +2d6.
      </Text>
    </Section>
  );
}
