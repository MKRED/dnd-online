import {
  HAZARD_TRIGGER,
  hazardLabel,
  MATERIALS,
  RESIZE_SIDES,
  SHAPE_LABELS,
  SHAPE_NAMES,
  SHAPES,
} from 'shared';
import { buildObjectGuide } from './objectGuide.js';

// Справка для модели: как устроены координаты, какие есть блоки и операции.
// Собирается из shared, чтобы не расходиться с тем, что реально принимает сервер.
export function buildBlockGuide(): string {
  const materials = Object.entries(MATERIALS).map(([name, m]) => {
    const traits = [
      m.opaque ? 'непрозрачный' : 'прозрачный',
      m.durability
        ? `КД ${m.durability.armorClass}, ХП ${m.durability.hitPoints}`
        : 'не разрушается атаками',
      m.flammable ? 'горит' : null,
      m.movementCost === 2 ? 'труднопроходимый' : null,
      m.hazard ? `опасный: ${hazardLabel(m.hazard)}` : null,
    ].filter(Boolean);
    return `- ${name} — ${m.label} (${traits.join(', ')})`;
  });
  const shapes = SHAPE_NAMES.map(
    (shape) =>
      `- ${shape} — ${SHAPE_LABELS[shape]}; коробки ${JSON.stringify(SHAPES[shape])}`,
  );

  return [
    'КООРДИНАТЫ',
    '- Клетка [x, y, z], целые числа, 1 клетка = 5 футов. y — высота. Север — -z, юг — +z, запад — -x, восток — +x.',
    '- Координаты от нуля: x, y и z не меньше 0. Земля — уровень y = 0, ниже неё строить нельзя.',
    '- У карты есть размер: ширина width по x и глубина depth по z (map_summary, поле size). Клетки — x от 0 до width − 1, z от 0 до depth − 1; операция за границей отклоняется. Высота общая для всех карт — до maxHeight уровней.',
    '- На блоке уровня y стоят на уровне y+1.',
    '',
    'ПРОПОРЦИИ ПОСТРОЕК (по вертикали — визуальный масштаб, как в Minecraft)',
    '- Этаж — 3 блока высоты в свету (пол y, стены y+1..y+3, перекрытие y+4); следующий этаж начинается через 4 уровня.',
    '- Дверь — 1×2 блока, окна — 1–2 блока на уровне y+2. Лестница на этаж — 4 ступени, над ними проём в перекрытии.',
    '- Рост существ (нужный просвет над головой): маленькие (полурослик, гном) — 1 блок, средние (человек, эльф, дварф) — 2, большие (огр) — 3, огромные (великан) — 4–5. Проходы и потолки строй под рост тех, кто ими пользуется.',
    '',
    'ИМЕНА БЛОКОВ',
    '- Куб — имя материала (stone), другие фигуры — материал_фигура (stone_stairs, wood_slab_top). «air» — воздух, им очищают клетки.',
    '',
    'МАТЕРИАЛЫ',
    ...materials,
    `- Опасный блок наносит урон тому, ${HAZARD_TRIGGER}. Это твёрдый пол: на лаве, кислоте, топи и воде стоят и бредут, как по мелководью, а не плывут. Яма с лавой — пол из лавы на дне; переход — камень поверх.`,
    '',
    'ФИГУРЫ (коробки внутри клетки: [minX, minY, minZ, maxX, maxY, maxZ] от 0 до 1, при повороте 0)',
    ...shapes,
    '- Поворот rotation: 0, 90, 180, 270 — по часовой стрелке при виде сверху. При 0 стена стоит у северного края клетки, ступени поднимаются к югу; 90 — стена у восточного края, ступени к западу; 180 — у южного, к северу; 270 — у западного, к востоку.',
    '',
    'ОПЕРАЦИИ (apply_ops принимает список, применяется целиком или не применяется вовсе, откатывается одним undo)',
    '- setBlock {at, block, rotation?}',
    '- fillBox {from, to, block, rotation?} — залить область (углы в любом порядке)',
    '- hollowBox {from, to, block, rotation?} — оболочка области (стены, пол и потолок), внутри — воздух',
    '- replace {from, to, match, block, rotation?} — заменить в области блоки match на block',
    `- resize {grow: {${RESIZE_SIDES.join(', ')}}, cut?} — изменить размер карты: сколько клеток добавить с каждой стороны (меньше нуля — убрать). Верха нет: высота и так растёт до maxHeight.`,
    '  - Рост с запада (west), севера (north) и снизу (down) сдвигает все блоки: старая клетка [0, 0, 0] станет [west, down, north]. Так строят подвал или ров под готовой картой: grow {down: 3} поднимает всё на 3 уровня.',
    '  - Срезанное с запада, севера и снизу удаляется. Срезанное с востока и юга при cut "keep" (по умолчанию) остаётся скрытым и вернётся, если карту снова расширить; при cut "delete" удаляется — вместе со скрытым раньше.',
    '  - Отменяется одним undo вместе с размером и сдвигом. Лимит объёма операции к resize не применяется. После resize в той же пачке координаты уже новые.',
    '',
    ...buildObjectGuide(),
  ].join('\n');
}
